"""Embed the game's sprite PNGs as data URIs in sprites.js.

The game is often opened straight from disk (file://), where browsers refuse to give
WebGL pixels from image files; data URIs are allowed. Re-run after changing a PNG:
    python3 assets/sprites/build_sprites_js.py
"""
import base64, pathlib

HERE = pathlib.Path(__file__).parent
NAMES = ['player_idle', 'player_walk', 'player_jump',
         'food_apple', 'food_banana', 'food_cake', 'food_golden_star']

lines = ['// Generated by assets/sprites/build_sprites_js.py — do not edit by hand.',
         'window.COIN_DASH_SPRITES = {']
for name in NAMES:
    data = base64.b64encode((HERE / f'{name}.png').read_bytes()).decode()
    lines.append(f"  {name}: 'data:image/png;base64,{data}',")
lines.append('};')
(HERE.parent.parent / 'sprites.js').write_text('\n'.join(lines) + '\n')
